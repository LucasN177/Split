create table if not exists public.split_groups (
    id          bigint generated by default as identity primary key,
    name        text not null,
    description text default '',
    created_at  timestamptz not null default now()
);

-- Die Gruppen-ID ist ein bigint (kompatibel zu einer bereits vorhandenen split_groups-Tabelle).
-- Falls die vorhandene id-Spalte keinen automatischen Wert hat, wird sie zur Identity-Spalte.
do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'split_groups' and column_name = 'id'
          and (is_identity = 'YES' or column_default is not null)
    ) then
        alter table public.split_groups alter column id add generated by default as identity;
        perform setval(pg_get_serial_sequence('public.split_groups', 'id'),
                       coalesce((select max(id) from public.split_groups), 0) + 1, false);
    end if;
end;
$$;

