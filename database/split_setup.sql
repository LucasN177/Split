-- Anzeigename eines Benutzers aus public.users (Vorname Nachname → Benutzername → E-Mail-Präfix)
create or replace function public.split_display_name(uid uuid)
returns text
language sql
stable
security definer set search_path = public
as $$
    select coalesce(
        (select coalesce(
                    nullif(trim(coalesce(u.vorname, '') || ' ' || coalesce(u.nachname, '')), ''),
                    nullif(u.username, ''))
         from public.users u where u.id = uid),
        (select nullif(split_part(coalesce(a.email, ''), '@', 1), '') from auth.users a where a.id = uid),
        'Ich'
    );
$$;

-- Ist der angemeldete Benutzer Mitglied (oder Ersteller) der Gruppe?
-- security definer verhindert eine Rekursion in den RLS-Policies.
create or replace function public.split_is_group_member(gid bigint)
returns boolean
language sql
stable
security definer set search_path = public
as $$
    select exists (
        select 1 from public.split_group_members
        where group_id = gid and user_id = auth.uid()
    ) or exists (
        select 1 from public.split_groups
        where id = gid and created_by = auth.uid()
    );
$$;

-- Ist der angemeldete Benutzer Admin (Ersteller) der Gruppe?
create or replace function public.split_is_group_admin(gid bigint)
returns boolean
language sql
stable
security definer set search_path = public
as $$
    select exists (select 1 from public.split_groups where id = gid and created_by = auth.uid());
$$;

-- Gruppen-ID aus einem Storage-Pfad "<group_id>/<datei>" (null bei ungültigem Pfad)
create or replace function public.split_storage_group(object_name text)
returns bigint
language plpgsql
immutable
as $$
begin
    return split_part(object_name, '/', 1)::bigint;
exception when others then
    return null;
end;
$$;

